def connect():
    import pymysql
    password = Path(os.environ["MYSQL_PASSWORD_FILE"]).read_text(encoding="utf-8").strip()
    return pymysql.connect(
        host=os.environ.get("MYSQL_HOST", "mysql"), port=int(os.environ.get("MYSQL_PORT", "3306")),
        user=os.environ.get("MYSQL_USER", "gummy_app"), password=password,
        database=os.environ.get("MYSQL_DATABASE", "gummybearing_v5_draft"),
        charset="utf8mb4", collation="utf8mb4_0900_as_cs", autocommit=False,
        connect_timeout=5, read_timeout=10, write_timeout=10,
        init_command="SET time_zone = '+09:00'", cursorclass=pymysql.cursors.DictCursor)


def serialize(row):
    result = {}
    for key, value in row.items():
        if value is None:
            value = ""
        elif isinstance(value, datetime):
            value = value.isoformat(timespec="minutes")
        elif isinstance(value, date):
            value = value.isoformat()
        elif isinstance(value, Decimal):
            value = format(value.normalize(), "f") if key == "estimated_hours" else float(value)
        elif key == "visual" and isinstance(value, str):
            value = json.loads(value)
        result[key] = value
    return result


def read_tables(tables):
    with connect() as conn, conn.cursor() as cur:
        result = {}
        for table in tables:
            if table not in KEYS:
                raise ValidationError("지원하지 않는 테이블입니다.")
            cur.execute(f"SELECT * FROM `{table}` ORDER BY `{KEYS[table]}`")
            raw = cur.fetchall()
            result[table] = audit_records(cur, table, raw)
        return result


def my_activity(user):
    """[MYPAGE ADD] Read only records linked to this authenticated account ID.

    Legacy name-only records remain in the shared history; never guess ownership.
    Calendar creators are recorded separately; assignee names never prove authorship.
    """
    with connect() as conn, conn.cursor() as cur:
        cur.execute(
            'SELECT i.* FROM inspections i '
            'JOIN gb_inspection_authors a ON a.inspection_id=i.inspection_id '
            'WHERE a.username=%s ORDER BY i.inspected_at DESC,i.inspection_id',
            (user['id'],))
        inspections = audit_records(cur, 'inspections', cur.fetchall())
        cur.execute(
            'SELECT f.* FROM follow_ups f '
            'JOIN gb_followup_authors a ON a.follow_up_id=f.follow_up_id '
            'WHERE a.username=%s AND f.inspection_id IS NULL '
            'ORDER BY a.created_at DESC,f.follow_up_id', (user['id'],))
        # Only independent calendar entries join the authored list. A follow-up
        # generated by an inspection must not count the same submission twice.
        calendar_schedules = audit_records(cur, 'follow_ups', cur.fetchall())
        cur.execute(
            'SELECT f.*,a.username AS completed_by_user_id,a.display_name AS completed_by,'
            'a.completed_at FROM follow_ups f '
            'JOIN gb_followup_completions a ON a.follow_up_id=f.follow_up_id '
            'WHERE a.username=%s ORDER BY a.completed_at DESC,f.follow_up_id',
            (user['id'],))
        completions = []
        for row in cur.fetchall():
            result = serialize(row)
            result['completed_at'] = row['completed_at'].isoformat(timespec='seconds') + '+09:00'
            completions.append(result)
        return {'inspections': inspections, 'calendar_schedules': calendar_schedules,
                'completions': completions,
                'counts': {'inspections': len(inspections),
                           'calendar_schedules': len(calendar_schedules),
                           'authored': len(inspections) + len(calendar_schedules),
                           'completions': len(completions)}}


